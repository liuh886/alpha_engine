"""Apply an Owner-authorized, minimal correction to a governed native preview bundle.

The QQQ v4.3 formal baseline is promoted from the persisted native preview
bundle under ``data/research/model_runs/`` by ``scripts/sync_formal_bundle_v2.py``.
The frozen prefix was built from a Yahoo ``^VIX`` vintage that emitted
non-session holiday stub rows. A session-calendar-filtered replay produces only
four ``decision_reason`` / ``executed_reason`` text differences; every decision
state, position state, label, overlay flag, weight, date and return is
unchanged.

This tool applies exactly those text cells to the **preview**
``performance.json`` and, for every ``executed_reason`` correction, the same
before/after value to the matching-date ``portfolio.json`` position rows. It
adds a deterministic ``baseline_correction`` block (with a separate
``positions_corrections`` inventory) to the preview ``lineage.json`` (which the
promotion preserves), and re-seals the preview manifest and preview catalog.
The formal root is then regenerated by the governed sync pipeline, never
hand-edited here.

The contract is deliberately narrow and fail-closed:

* only ``decision_reason`` and ``executed_reason`` text may change;
* a difference on any other gate field, a weight, a state, a label, a date, a
  row count, or the observed window aborts the run;
* zero differences is an error unless the same policy already corrected the run;
* at most eight differing cells are accepted as a sanity bound;
* the corrected ``performance.json`` is re-serialized with the bundle writer's
  own canonical encoder so byte compatibility is preserved;
* only exact references inside the native preview root are rewritten; any
  unhandled reference aborts before a write.

The tool never recomputes economics and never touches another model or run.
"""

