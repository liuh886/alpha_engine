# The formal gate compares exactly these scalar decision fields plus every
# weight column present in the report.
GATE_SCALAR_FIELDS = (
    "decision_state",
    "position_state",
    "position_label",
    "decision_reason",
    "executed_reason",
    "panic_repair_active",
    "slow_bear_defense_active",
)
CORRECTABLE_TEXT_FIELDS = ("decision_reason", "executed_reason")
MAX_DIFF_CELLS = 8
NATIVE_ROOT_RELATIVE = Path("data/research/model_runs")


class FormalBaselineCorrectionError(ValueError):
    """Raised when a formal baseline correction would exceed its narrow contract."""


def _read_json(path: Path, *, label: str) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise FormalBaselineCorrectionError(f"invalid {label}: {path}") from exc
    if not isinstance(value, dict):
        raise FormalBaselineCorrectionError(f"{label} root must be an object: {path}")
    return value


def _relative(repository: Path, path: Path) -> str:
    try:
        return path.resolve().relative_to(repository).as_posix()
    except ValueError:
        return path.as_posix()


def _report_rows(payload: Mapping[str, Any], *, label: str) -> list[dict[str, Any]]:
    rows = payload.get("report")
    if not isinstance(rows, list) or not rows:
        raise FormalBaselineCorrectionError(f"{label} performance report is missing")
    if not all(isinstance(row, Mapping) for row in rows):
        raise FormalBaselineCorrectionError(f"{label} performance report rows are invalid")
    return [dict(row) for row in rows]


def _row_key_sets(rows: Sequence[Mapping[str, Any]], *, label: str) -> set[str]:
    expected = set(rows[0])
    for index, row in enumerate(rows):
        if set(row) != expected:
            raise FormalBaselineCorrectionError(
                f"{label} row {index} column set is inconsistent"
            )
    return expected


def _strictly_increasing(dates: Sequence[str]) -> bool:
    return all(left < right for left, right in zip(dates, dates[1:]))


def _differences(
    primary_rows: Sequence[Mapping[str, Any]],
    replay_rows: Sequence[Mapping[str, Any]],
    *,
    gate_fields: Sequence[str],
) -> list[dict[str, Any]]:
    differences: list[dict[str, Any]] = []
    for primary, replay in zip(primary_rows, replay_rows):
        if str(primary["date"]) != str(replay["date"]):
            raise FormalBaselineCorrectionError(
                "replay dates are not aligned to the frozen baseline: "
                f"{primary['date']} != {replay['date']}"
            )
        for field in gate_fields:
            before = primary.get(field)
            after = replay.get(field)
            if before != after:
                differences.append(
                    {
                        "date": str(primary["date"]),
                        "field": field,
                        "before": before,
                        "after": after,
                    }
                )
    return differences


def _validate_differences(
    differences: Sequence[Mapping[str, Any]],
    *,
    primary_rows: Sequence[Mapping[str, Any]],
) -> list[dict[str, str]]:
    if not differences:
        return []
    if len(differences) > MAX_DIFF_CELLS:
        raise FormalBaselineCorrectionError(
            f"correction touches {len(differences)} cells, exceeding the "
            f"{MAX_DIFF_CELLS}-cell sanity bound"
        )
    known_dates = {str(row["date"]) for row in primary_rows}
    seen: set[tuple[str, str]] = set()
    cleaned: list[dict[str, str]] = []
    for difference in differences:
        date = str(difference["date"])
        field = str(difference["field"])
        if field not in CORRECTABLE_TEXT_FIELDS:
            raise FormalBaselineCorrectionError(
                f"refusing non-reason difference on {date}: {field}"
            )
        before = difference["before"]
        after = difference["after"]
        if not isinstance(before, str) or not isinstance(after, str):
            raise FormalBaselineCorrectionError(
                f"reason difference on {date}/{field} is not text"
            )
        if (date, field) in seen:
            raise FormalBaselineCorrectionError(f"duplicate difference on {date}/{field}")
        seen.add((date, field))
        if date not in known_dates:
            raise FormalBaselineCorrectionError(f"difference date is absent: {date}")
        cleaned.append({"date": date, "field": field, "before": before, "after": after})
    cleaned.sort(key=lambda row: (row["date"], row["field"]))
    return cleaned


def _validate_replay_structure(
    primary: Mapping[str, Any],
    replay: Mapping[str, Any],
    *,
    primary_rows: Sequence[Mapping[str, Any]],
    replay_rows: Sequence[Mapping[str, Any]],
    window_start: str,
    window_end: str,
) -> list[str]:
    if len(primary_rows) != len(replay_rows):
        raise FormalBaselineCorrectionError(
            f"replay row count {len(replay_rows)} != baseline {len(primary_rows)}"
        )
    primary_dates = [str(row["date"]) for row in primary_rows]
    replay_dates = [str(row["date"]) for row in replay_rows]
    if primary_dates != replay_dates:
        raise FormalBaselineCorrectionError("replay ordered dates do not match the baseline")
    if not _strictly_increasing(primary_dates):
        raise FormalBaselineCorrectionError("baseline dates are not strictly increasing")
    if primary_dates[0] != window_start or primary_dates[-1] != window_end:
        raise FormalBaselineCorrectionError(
            "baseline trace boundaries do not match the manifest comparability window"
        )

    primary_keys = _row_key_sets(primary_rows, label="baseline")
    replay_keys = _row_key_sets(replay_rows, label="replay")
    if primary_keys != replay_keys:
        raise FormalBaselineCorrectionError(
            "replay column set differs from the baseline: "
            f"missing={sorted(primary_keys - replay_keys)}, "
            f"extra={sorted(replay_keys - primary_keys)}"
        )

    primary_range = primary.get("date_range")
    if not isinstance(primary_range, Mapping):
        raise FormalBaselineCorrectionError("baseline performance date_range is missing")
    if (
        str(primary_range.get("start")) != window_start
        or str(primary_range.get("end")) != window_end
    ):
        raise FormalBaselineCorrectionError(
            "baseline performance date_range does not match the comparability window"
        )
    replay_range = replay.get("date_range")
    if replay_range is not None:
        if not isinstance(replay_range, Mapping):
            raise FormalBaselineCorrectionError("replay date_range is invalid")
        if (
            str(replay_range.get("start")) != window_start
            or str(replay_range.get("end")) != window_end
        ):
            raise FormalBaselineCorrectionError(
                "replay comparability window does not match the baseline"
            )
    replay_comparability = replay.get("comparability_key")
    if replay_comparability is not None:
        if not isinstance(replay_comparability, Mapping):
            raise FormalBaselineCorrectionError("replay comparability_key is invalid")
        if (
            str(replay_comparability.get("start")) != window_start
            or str(replay_comparability.get("end")) != window_end
        ):
            raise FormalBaselineCorrectionError(
                "replay comparability_key window does not match the baseline"
            )

    missing = [field for field in GATE_SCALAR_FIELDS if field not in primary_keys]
    if missing:
        raise FormalBaselineCorrectionError(f"baseline is missing gate fields: {missing}")
    gate_fields = [field for field in GATE_SCALAR_FIELDS if field in primary_keys]
    gate_fields.extend(sorted(key for key in primary_keys if key.startswith("weight_")))
    return gate_fields


def _session_filter_evidence(replay: Mapping[str, Any]) -> dict[str, Any]:
    """Return deterministic #1437 session-filter evidence when the replay carries it."""

    evidence = replay.get("signal_reference_session_filter")
    if not isinstance(evidence, Mapping):
        return {}
    symbols = evidence.get("symbols")
    if not isinstance(symbols, Mapping):
        return {}
    normalized: dict[str, Any] = {
        "policy_id": str(evidence.get("policy_id") or ""),
        "authority_symbol": str(evidence.get("authority_symbol") or ""),
        "authority_session_count": evidence.get("authority_session_count"),
        "symbols": {},
    }
    for symbol, value in sorted(symbols.items()):
        if not isinstance(value, Mapping):
            continue
        normalized["symbols"][str(symbol)] = {
            "input_rows": value.get("input_rows"),
            "retained_rows": value.get("retained_rows"),
            "removed_count": value.get("removed_count"),
            "removed_dates": sorted(str(item) for item in value.get("removed_dates") or []),
        }
    return normalized


def _removed_non_session_dates(session_filter: Mapping[str, Any]) -> list[str]:
    removed: set[str] = set()
    symbols = session_filter.get("symbols")
    if isinstance(symbols, Mapping):
        for value in symbols.values():
            if isinstance(value, Mapping):
                removed.update(str(item) for item in value.get("removed_dates") or [])
    return sorted(removed)


def _compact_data_identity(replay: Mapping[str, Any]) -> dict[str, Any]:
    """Retain only the deterministic provider-vintage identity of the replay."""

    identity = replay.get("data_identity")
    if not isinstance(identity, Mapping):
        return {}
    return {
        "mode": identity.get("mode"),
        "bundle_id": identity.get("bundle_id"),
        "component_id": identity.get("component_id"),
        "manifest_sha256": identity.get("manifest_sha256"),
        "common_history_start": identity.get("common_history_start"),
        "common_history_end": identity.get("common_history_end"),
        "selected_providers": identity.get("selected_providers"),
        "symbols": identity.get("symbols"),
        "roles": identity.get("roles"),
    }


def _report_by_date(rows: Sequence[Mapping[str, Any]]) -> dict[str, Mapping[str, Any]]:
    return {str(row["date"]): row for row in rows}


def _validate_position_row(
    row: Mapping[str, Any], report_row: Mapping[str, Any], *, date: str
) -> None:
    """Cross-check one position row against the report row for the same date."""

    instrument = str(row.get("instrument") or "")
    if not instrument:
        raise FormalBaselineCorrectionError(f"position instrument is missing on {date}")
    weight_key = f"weight_{instrument}"
    if weight_key not in report_row:
        raise FormalBaselineCorrectionError(
            f"position instrument has no report weight on {date}: {instrument}"
        )
    for field in (
        "position_state",
        "position_label",
        "panic_repair_active",
        "slow_bear_defense_active",
    ):
        if row.get(field) != report_row.get(field):
            raise FormalBaselineCorrectionError(
                f"position {field} differs from the report on {date}"
            )
    try:
        weight = float(row.get("weight"))
        expected_weight = float(report_row[weight_key])
    except (TypeError, ValueError) as exc:
        raise FormalBaselineCorrectionError(
            f"position weight is not numeric on {date}"
        ) from exc
    if not math.isclose(weight, expected_weight, rel_tol=0.0, abs_tol=1e-12):
        raise FormalBaselineCorrectionError(
            f"position {instrument} weight differs from the report on {date}"
        )
    price = row.get("price")
    if (
        not isinstance(price, (int, float))
        or isinstance(price, bool)
        or not math.isfinite(float(price))
        or float(price) <= 0.0
    ):
        raise FormalBaselineCorrectionError(
            f"position price is not a positive finite number on {date}"
        )


def _assert_only_position_reasons_changed(
    original: Mapping[str, Any],
    corrected: Mapping[str, Any],
    *,
    changed_dates: set[str],
) -> None:
    """Fail closed unless only executed_reason on changed dates differs."""

    if set(original) != set(corrected):
        raise FormalBaselineCorrectionError("positions correction changed the section shape")
    original_positions = original.get("positions")
    corrected_positions = corrected.get("positions")
    if not isinstance(original_positions, list) or not isinstance(corrected_positions, list):
        raise FormalBaselineCorrectionError("positions correction lost the position rows")
    if len(original_positions) != len(corrected_positions):
        raise FormalBaselineCorrectionError("positions correction changed the row count")
    for before, after in zip(original_positions, corrected_positions):
        if set(before) != set(after):
            raise FormalBaselineCorrectionError("positions correction changed a row shape")
        date = str(before.get("date"))
        for field in before:
            if date in changed_dates and field == "executed_reason":
                continue
            if before[field] != after[field]:
                raise FormalBaselineCorrectionError(
                    f"positions correction changed a non-reason field on {date}: {field}"
                )
    for key in original:
        if key != "positions" and original[key] != corrected[key]:
            raise FormalBaselineCorrectionError(
                f"positions correction changed a portfolio field: {key}"
            )


def _positions_plan(
    portfolio: Mapping[str, Any] | None,
    report_by_date: Mapping[str, Mapping[str, Any]],
    executed_reason_corrections: Sequence[Mapping[str, str]],
) -> tuple[list[dict[str, Any]], dict[str, Any] | None]:
    """Return pending executed_reason position corrections and the corrected section."""

    if not executed_reason_corrections:
        return [], None
    if not isinstance(portfolio, Mapping):
        raise FormalBaselineCorrectionError(
            "executed_reason corrections require an available positions section"
        )
    positions = portfolio.get("positions")
    if not isinstance(positions, list) or not positions:
        raise FormalBaselineCorrectionError("positions section is absent or empty")

    corrections: list[dict[str, Any]] = []
    pending: list[dict[str, Any]] = []
    for correction in sorted(
        executed_reason_corrections, key=lambda row: (row["date"], row["field"])
    ):
        date = str(correction["date"])
        field = str(correction["field"])
        before = str(correction["before"])
        after = str(correction["after"])
        if field != "executed_reason":
            raise FormalBaselineCorrectionError(
                f"positions only mirror executed_reason: {field}"
            )
        if date not in report_by_date:
            raise FormalBaselineCorrectionError(f"position correction date is absent: {date}")
        matched = [row for row in positions if str(row.get("date")) == date]
        if not matched:
            raise FormalBaselineCorrectionError(f"no positions rows for corrected date {date}")
        values = {str(row.get("executed_reason")) for row in matched}
        if not values <= {before, after}:
            raise FormalBaselineCorrectionError(
                f"position executed_reason is neither {before!r} nor {after!r} on {date}"
            )
        if len(values) != 1:
            raise FormalBaselineCorrectionError(
                f"ambiguous position executed_reason on {date}: {sorted(values)}"
            )
        for row in matched:
            _validate_position_row(row, report_by_date[date], date=date)
        entry = {
            "date": date,
            "field": field,
            "before": before,
            "after": after,
            "row_count": len(matched),
        }
        corrections.append(entry)
        if next(iter(values)) == before:
            pending.append(entry)

    if not pending:
        return corrections, None
    if len(pending) != len(corrections):
        raise FormalBaselineCorrectionError(
            "positions are only partially corrected; refusing an ambiguous rewrite"
        )

    corrected = copy.deepcopy(dict(portfolio))
    by_date: dict[str, list[dict[str, Any]]] = {}
    for row in corrected["positions"]:
        by_date.setdefault(str(row.get("date")), []).append(row)
    for entry in pending:
        for row in by_date[entry["date"]]:
            row["executed_reason"] = entry["after"]
    _assert_only_position_reasons_changed(
        portfolio, corrected, changed_dates={entry["date"] for entry in pending}
    )
    return corrections, corrected


def _verify_recorded_report_cells(
    block: Mapping[str, Any], *, primary_rows: Sequence[Mapping[str, Any]]
) -> list[dict[str, Any]]:
    recorded = block.get("corrections")
    if not isinstance(recorded, list) or not recorded:
        raise FormalBaselineCorrectionError("recorded baseline correction has no cells")
    by_date = _report_by_date(primary_rows)
    for entry in recorded:
        if not isinstance(entry, Mapping):
            raise FormalBaselineCorrectionError("recorded correction cell is invalid")
        date = str(entry.get("date"))
        field = str(entry.get("field"))
        if date not in by_date:
            raise FormalBaselineCorrectionError(f"recorded correction date is absent: {date}")
        if str(by_date[date].get(field)) != str(entry.get("after")):
            raise FormalBaselineCorrectionError(
                f"baseline no longer holds the recorded correction on {date}/{field}"
            )
    return [dict(entry) for entry in recorded]


def _existing_correction(
    lineage: Mapping[str, Any], *, policy_id: str
) -> Mapping[str, Any] | None:
    block = lineage.get("baseline_correction")
    if block is None:
        return None
    if not isinstance(block, Mapping):
        raise FormalBaselineCorrectionError("baseline_correction lineage block is invalid")
    if str(block.get("policy_id")) != policy_id:
        raise FormalBaselineCorrectionError(
            "a different baseline correction is already recorded in lineage: "
            f"{block.get('policy_id')!r}"
        )
    return block


def _scan_references(
    native_root: Path,
    *,
    old_bundle_id: str,
    old_manifest_sha256: str,
    allowed_rewrites: set[Path],
) -> list[str]:
    """Return unhandled references to the old identity inside the native root."""

    needles = (old_bundle_id, old_manifest_sha256)
    unhandled: list[str] = []
    for path in sorted(native_root.rglob("*.json")):
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if not any(needle in text for needle in needles):
            continue
        resolved = path.resolve()
        if resolved in allowed_rewrites:
            continue
        unhandled.append(resolved.as_posix())
    return unhandled


def _load_preview_run(
    repository: Path, native_root: Path, model_version_id: str
) -> tuple[
    dict[str, Any],
    Path,
    dict[str, Any],
    Path,
    dict[str, Any],
    Path,
    dict[str, Any],
    dict[str, Any],
    Path | None,
    dict[str, Any] | None,
]:
    catalog_path = native_root / "catalog.json"
    catalog = _read_json(catalog_path, label="native preview catalog")
    validate_catalog(catalog)
    if (
        catalog.get("channel") != "preview"
        or catalog.get("research_only") is not True
        or catalog.get("trade_ready") is not False
    ):
        raise FormalBaselineCorrectionError("native root is not a preview Bundle v2 catalog")
    records = [
        record
        for record in catalog.get("records", [])
        if str(record.get("model_version_id")) == model_version_id
    ]
    if len(records) != 1:
        raise FormalBaselineCorrectionError(
            f"expected one preview catalog record for {model_version_id}, found {len(records)}"
        )
    record = records[0]
    if record.get("publication_status") != "ci_validated_preview":
        raise FormalBaselineCorrectionError("native record is not a CI-validated preview")
    manifest_path = (catalog_path.parent / str(record.get("manifest_path") or "")).resolve()
    try:
        manifest_path.relative_to(native_root)
    except ValueError as exc:
        raise FormalBaselineCorrectionError("preview manifest escapes the native root") from exc
    if not manifest_path.is_file():
        raise FormalBaselineCorrectionError("preview manifest is missing")
    if sha256_bytes(manifest_path.read_bytes()) != record.get("manifest_sha256"):
        raise FormalBaselineCorrectionError("preview manifest digest does not match the catalog")

    manifest = _read_json(manifest_path, label="preview manifest")
    validate_manifest(manifest)
    for field in (
        "model_family_id",
        "model_version_id",
        "model_kind",
        "run_id",
        "bundle_id",
        "evidence_cutoff",
        "publication_status",
    ):
        if manifest.get(field) != record.get(field):
            raise FormalBaselineCorrectionError(
                f"preview manifest/catalog mismatch on {field}"
            )
    if (
        manifest.get("publication_channel") != "preview"
        or manifest.get("publication_status") != "ci_validated_preview"
        or manifest.get("research_only") is not True
        or manifest.get("trade_ready") is not False
    ):
        raise FormalBaselineCorrectionError("preview manifest boundary is invalid")

    run_dir = manifest_path.parent
    for section in manifest["sections"]:
        if section.get("availability_status") != "available":
            continue
        path = run_dir / str(section.get("path") or "")
        if not path.is_file():
            raise FormalBaselineCorrectionError(
                f"preview section is missing: {section.get('section_id')}"
            )
        data = path.read_bytes()
        if len(data) != section.get("byte_size") or sha256_bytes(data) != section.get("sha256"):
            raise FormalBaselineCorrectionError(
                f"preview section identity mismatch: {section.get('section_id')}"
            )
    performance_path = run_dir / "performance.json"
    lineage_path = run_dir / "lineage.json"
    performance = _read_json(performance_path, label="preview performance")
    lineage = _read_json(lineage_path, label="preview lineage")
    portfolio_declaration = next(
        (
            section
            for section in manifest["sections"]
            if section.get("section_id") == "portfolio"
        ),
        None,
    )
    if portfolio_declaration is None or portfolio_declaration.get("availability_status") != "available":
        portfolio_path = None
        portfolio = None
    else:
        portfolio_path = run_dir / str(portfolio_declaration.get("path") or "portfolio.json")
        portfolio = _read_json(portfolio_path, label="preview portfolio")
    return (
        record,
        catalog_path,
        catalog,
        manifest_path,
        manifest,
        run_dir,
        performance,
        lineage,
        portfolio_path,
        portfolio,
    )


def correct_formal_baseline_prefix(
    *,
    repository_root: str | Path,
    model_version_id: str,
    policy_id: str,
    authorization: str,
    replay_performance: str | Path,
    native_root: str | Path = NATIVE_ROOT_RELATIVE,
    corrected_at: str | None = None,
    dry_run: bool = False,
) -> dict[str, Any]:
    """Apply the governed preview correction and return a deterministic receipt."""

    repository = Path(repository_root).resolve()
    native = Path(native_root)
    native = (repository / native).resolve() if not native.is_absolute() else native.resolve()
    try:
        native.relative_to(repository)
    except ValueError as exc:
        raise FormalBaselineCorrectionError("native root escapes the repository") from exc
    if not policy_id.strip():
        raise FormalBaselineCorrectionError("policy_id is required")
    if not authorization.strip():
        raise FormalBaselineCorrectionError("authorization is required")

    (
        record,
        catalog_path,
        catalog,
        manifest_path,
        manifest,
        run_dir,
        performance,
        lineage,
        portfolio_path,
        portfolio,
    ) = _load_preview_run(repository, native, model_version_id)
    performance_path = run_dir / "performance.json"
    lineage_path = run_dir / "lineage.json"

    original_performance_bytes = performance_path.read_bytes()
    original_lineage_bytes = lineage_path.read_bytes()
    original_portfolio_bytes = (
        portfolio_path.read_bytes() if portfolio_path is not None else None
    )
    for label, payload, original in (
        ("performance", performance, original_performance_bytes),
        ("lineage", lineage, original_lineage_bytes),
    ):
        if canonical_json_bytes(payload) != original:
            raise FormalBaselineCorrectionError(
                f"preview {label}.json is not in the bundle writer's canonical encoding"
            )
    if portfolio is not None and original_portfolio_bytes is not None:
        if canonical_json_bytes(portfolio) != original_portfolio_bytes:
            raise FormalBaselineCorrectionError(
                "preview portfolio.json is not in the bundle writer's canonical encoding"
            )

    replay_path = Path(replay_performance)
    if not replay_path.is_absolute():
        replay_path = (Path.cwd() / replay_path).resolve()
    replay = _read_json(replay_path, label="replay performance")

    primary_rows = _report_rows(performance, label="baseline")
    replay_rows = _report_rows(replay, label="replay")
    comparability = manifest.get("comparability_key")
    if not isinstance(comparability, Mapping):
        raise FormalBaselineCorrectionError("manifest comparability_key is missing")
    window_start = str(comparability.get("start"))
    window_end = str(comparability.get("end"))

    gate_fields = _validate_replay_structure(
        performance,
        replay,
        primary_rows=primary_rows,
        replay_rows=replay_rows,
        window_start=window_start,
        window_end=window_end,
    )
    raw_differences = _differences(primary_rows, replay_rows, gate_fields=gate_fields)
    report_differences = _validate_differences(raw_differences, primary_rows=primary_rows)

    old_bundle_id = str(manifest["bundle_id"])
    old_manifest_sha256 = sha256_bytes(manifest_path.read_bytes())
    existing_block = _existing_correction(lineage, policy_id=policy_id)

    if report_differences:
        if existing_block is not None:
            raise FormalBaselineCorrectionError(
                "the baseline is already corrected but the replay now disagrees; "
                "refusing to re-apply"
            )
        target_corrections = report_differences
        corrected_at = corrected_at or f"{manifest['evidence_cutoff']}T00:00:00Z"
    else:
        if existing_block is None:
            raise FormalBaselineCorrectionError(
                "replay matches the baseline exactly; there is nothing to correct"
            )
        target_corrections = _verify_recorded_report_cells(
            existing_block, primary_rows=primary_rows
        )
        recorded_at = existing_block.get("corrected_at")
        corrected_at = corrected_at or (
            str(recorded_at)
            if recorded_at
            else f"{manifest['evidence_cutoff']}T00:00:00Z"
        )

    executed_reason_corrections = [
        correction
        for correction in target_corrections
        if str(correction.get("field")) == "executed_reason"
    ]
    positions_corrections, corrected_portfolio = _positions_plan(
        portfolio,
        _report_by_date(primary_rows),
        executed_reason_corrections,
    )
    positions_changed = corrected_portfolio is not None
    recorded_positions = (
        existing_block.get("positions_corrections")
        if existing_block is not None
        else None
    )
    positions_inventory_changed = recorded_positions != positions_corrections

    if (
        not report_differences
        and not positions_changed
        and not positions_inventory_changed
    ):
        return {
            "status": "already_corrected",
            "model_version_id": model_version_id,
            "policy_id": policy_id,
            "preview_root": _relative(repository, native),
            "bundle_id": old_bundle_id,
            "manifest_sha256": old_manifest_sha256,
            "differences": [],
            "positions_corrections": [],
            "written": [],
            "research_only": True,
            "trade_ready": False,
        }
    replay_sha256 = sha256_bytes(replay_path.read_bytes())
    session_filter = _session_filter_evidence(replay)
    removed_dates = _removed_non_session_dates(session_filter)
    data_identity = _compact_data_identity(replay)

    corrected_performance = copy.deepcopy(performance)
    corrected_by_date = _report_by_date(corrected_performance["report"])
    for difference in report_differences:
        corrected_by_date[difference["date"]][difference["field"]] = difference["after"]
    corrected_performance_bytes = canonical_json_bytes(corrected_performance)

    corrected_lineage = copy.deepcopy(lineage)
    if existing_block is None:
        corrected_lineage["baseline_correction"] = {
            "policy_id": policy_id,
            "authorization": authorization,
            "corrected_at": corrected_at,
            "replay_source": {
                "description": (
                    "session-calendar-filtered re-run of the frozen v4.33 joint strategy "
                    "using the governed strategy data bundle with the #1437 "
                    "^VIX/^VXN session filter applied"
                ),
                "sha256": replay_sha256,
                "row_count": len(primary_rows),
                "window_start": window_start,
                "window_end": window_end,
                "data_identity": data_identity,
            },
            "session_filter": session_filter,
            "corrections": target_corrections,
            "positions_corrections": positions_corrections,
            "removed_non_session_dates": removed_dates,
            "unchanged_statement": (
                "Every decision_state, position_state, position_label, "
                "panic_repair_active, slow_bear_defense_active, weight_* value, date, "
                "return, and row count is unchanged; only decision_reason and "
                "executed_reason labels differ from the original frozen prefix, in the "
                "report and in the matching-date position rows."
            ),
            "model_selection_reopened": False,
            "research_only": True,
            "trade_ready": False,
        }
    else:
        block = copy.deepcopy(dict(existing_block))
        block["positions_corrections"] = positions_corrections
        corrected_lineage["baseline_correction"] = block
    corrected_lineage_bytes = canonical_json_bytes(corrected_lineage)

    if corrected_portfolio is None:
        corrected_portfolio_bytes = original_portfolio_bytes
    else:
        corrected_portfolio_bytes = canonical_json_bytes(corrected_portfolio)

    corrected_manifest = copy.deepcopy(manifest)
    section_paths = {
        "performance": "performance.json",
        "portfolio": "portfolio.json",
        "lineage": "lineage.json",
    }
    section_bytes: dict[str, bytes] = {
        "performance": corrected_performance_bytes,
        "lineage": corrected_lineage_bytes,
    }
    if corrected_portfolio_bytes is not None:
        section_bytes["portfolio"] = corrected_portfolio_bytes
    for section in corrected_manifest["sections"]:
        section_id = str(section.get("section_id") or "")
        if section_id not in section_bytes:
            continue
        if section.get("availability_status") != "available":
            raise FormalBaselineCorrectionError(
                f"{section_id} section is unexpectedly unavailable"
            )
        if section.get("path") != section_paths[section_id]:
            raise FormalBaselineCorrectionError(
                f"unexpected {section_id} section path"
            )
        body = section_bytes[section_id]
        section["sha256"] = sha256_bytes(body)
        section["byte_size"] = len(body)
    corrected_manifest["bundle_id"] = compute_bundle_id(corrected_manifest)
    validate_manifest(corrected_manifest)
    corrected_manifest_bytes = canonical_json_bytes(corrected_manifest)
    new_bundle_id = str(corrected_manifest["bundle_id"])
    new_manifest_sha256 = sha256_bytes(corrected_manifest_bytes)

    record["bundle_id"] = new_bundle_id
    record["manifest_sha256"] = new_manifest_sha256
    validate_catalog(catalog)
    corrected_catalog_bytes = canonical_json_bytes(catalog)

    allowed_rewrites = {
        performance_path.resolve(),
        lineage_path.resolve(),
        manifest_path.resolve(),
        catalog_path.resolve(),
    }
    if portfolio_path is not None:
        allowed_rewrites.add(portfolio_path.resolve())
    unhandled = _scan_references(
        native,
        old_bundle_id=old_bundle_id,
        old_manifest_sha256=old_manifest_sha256,
        allowed_rewrites=allowed_rewrites,
    )
    if unhandled:
        raise FormalBaselineCorrectionError(
            "unhandled content-addressed references must be resolved before correction: "
            + ", ".join(_relative(repository, Path(value)) for value in unhandled)
        )

    old_manifest_bytes = manifest_path.read_bytes()
    old_catalog_bytes = catalog_path.read_bytes()
    plan_candidates: list[tuple[Path, bytes, bytes]] = [
        (performance_path, original_performance_bytes, corrected_performance_bytes),
        (lineage_path, original_lineage_bytes, corrected_lineage_bytes),
        (manifest_path, old_manifest_bytes, corrected_manifest_bytes),
        (catalog_path, old_catalog_bytes, corrected_catalog_bytes),
    ]
    if (
        portfolio_path is not None
        and original_portfolio_bytes is not None
        and corrected_portfolio_bytes is not None
    ):
        plan_candidates.append(
            (portfolio_path, original_portfolio_bytes, corrected_portfolio_bytes)
        )
    planned = [
        {
            "path": _relative(repository, path),
            "before_sha256": sha256_bytes(before),
            "after_sha256": sha256_bytes(after),
            "byte_size": len(after),
        }
        for path, before, after in plan_candidates
        if before != after
    ]

    receipt: dict[str, Any] = {
        "status": "dry_run" if dry_run else "corrected",
        "model_version_id": model_version_id,
        "policy_id": policy_id,
        "authorization": authorization,
        "corrected_at": corrected_at,
        "preview_root": _relative(repository, native),
        "differences": report_differences,
        "report_corrections": target_corrections,
        "positions_corrections": positions_corrections,
        "positions_changed": positions_changed,
        "removed_non_session_dates": removed_dates,
        "session_filter": session_filter,
        "replay_data_identity": data_identity,
        "bundle_id": {"before": old_bundle_id, "after": new_bundle_id},
        "manifest_sha256": {"before": old_manifest_sha256, "after": new_manifest_sha256},
        "planned_writes": planned,
        "downstream": [
            "python -m scripts.sync_formal_bundle_v2 ... (regenerate the formal root)",
            "python -m src.artifacts.model_run_decision --formal-catalog ... --output ...",
            "python -m scripts.derive_formal_benchmark_excess --repository-root .",
        ],
        "model_selection_reopened": False,
        "research_only": True,
        "trade_ready": False,
    }
    if dry_run:
        return receipt

    performance_path.write_bytes(corrected_performance_bytes)
    lineage_path.write_bytes(corrected_lineage_bytes)
    manifest_path.write_bytes(corrected_manifest_bytes)
    catalog_path.write_bytes(corrected_catalog_bytes)
    if (
        portfolio_path is not None
        and corrected_portfolio_bytes is not None
        and corrected_portfolio_bytes != original_portfolio_bytes
    ):
        portfolio_path.write_bytes(corrected_portfolio_bytes)

    residual = _scan_references(
        native,
        old_bundle_id=old_bundle_id,
        old_manifest_sha256=old_manifest_sha256,
        allowed_rewrites=set(),
    )
    if residual:
        raise FormalBaselineCorrectionError(
            "residual content-addressed references remain after correction: "
            + ", ".join(_relative(repository, Path(value)) for value in residual)
        )

    receipt["written"] = [entry["path"] for entry in planned]
    return receipt


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository-root", type=Path, default=Path.cwd())
    parser.add_argument("--model-version-id", required=True)
    parser.add_argument("--policy-id", required=True)
    parser.add_argument("--authorization", required=True)
    parser.add_argument("--replay-performance", type=Path, required=True)
    parser.add_argument(
        "--native-root",
        type=Path,
        default=NATIVE_ROOT_RELATIVE,
        help="Persisted native preview Bundle v2 root (the sync's sole evidence input).",
    )
    parser.add_argument("--corrected-at", default=None)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)
    try:
        receipt = correct_formal_baseline_prefix(
            repository_root=args.repository_root,
            model_version_id=args.model_version_id,
            policy_id=args.policy_id,
            authorization=args.authorization,
            replay_performance=args.replay_performance,
            native_root=args.native_root,
            corrected_at=args.corrected_at,
            dry_run=args.dry_run,
        )
    except FormalBaselineCorrectionError as exc:
        print(json.dumps({"status": "refused", "error": str(exc)}), file=sys.stderr)
        return 2
    print(json.dumps(receipt, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
